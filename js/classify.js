const firstHit = (text, list) => list.find(([w]) => text.includes(w));

export function suggest(desc) {
  const text = (desc || '').replace(/\s+/g, ' ').trim();
  const cat = firstHit(text, CAT_WORDS);
  const col = firstHit(text, COLORS);
  const out = {
    name: text.split(/[,，/]/)[0].trim(),
    category: cat ? cat[1] : null,
    type: cat ? cat[0] : '',
    color: col ? col[1] : '',
    hex: col ? col[2] : '#cfc8bd',
    length: null, thickness: null, size: null, formality: 'both',
  };
  // 기장
  if (/무릎\s*아래|미디/.test(text)) out.length = '미디';
  else if (/미니|숏|짧/.test(text)) out.length = '미니';
  else if (/무릎/.test(text)) out.length = '무릎';
  else if (/롱|맥시|긴\s*(치마|스커트|기장)/.test(text)) out.length = '롱';
  else if (out.category === '하의' && /슬랙스|바지|팬츠|데님|청바지|레깅스/.test(text) && !/반바지|쇼츠/.test(text)) out.length = '롱';
  // 두께
  if (/얇|시스루|린넨|여름/.test(text)) out.thickness = '얇음';
  else if (/두꺼|두툼|기모|패딩|겨울|헤비|울\s*코트|캐시미어/.test(text)) out.thickness = '두꺼움';
  else if (/보통|중간/.test(text)) out.thickness = '보통';
  // 가방 크기
  if (/큰|빅|쇼퍼|토트|출근용\s*가방|노트북/.test(text)) out.size = '큰 가방';
  else if (/작은|스몰|미니백|크로스|클러치/.test(text)) out.size = '작은 가방';
  // 용도
  if (/출근|오피스|회사|비즈니스|포멀|하객/.test(text)) out.formality = /캐주얼|데일리|휴무|주말/.test(text) ? 'both' : 'work';
  else if (/캐주얼|데일리|휴무|주말|운동/.test(text)) out.formality = 'casual';
  return out;
}

// 카테고리마다 꼭 받아야 하는 값
export function requiredFields(category) {
  if (category === '하의' || category === '원피스') return ['length'];
  if (category === '아우터') return ['thickness'];
  if (category === '가방') return ['size'];
  return [];
}
